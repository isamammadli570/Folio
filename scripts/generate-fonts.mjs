// Writes src/fonts.css (and the small files in src/assets/fonts) from the @fontsource packages.
//
// Azerbaijani needs a handful of letters outside basic Latin (ə Ə ğ Ğ İ ş Ş) plus the manat sign. Fontsource keeps them
// in its "latin-ext" files, 20–85 kB each, so every page used to download all of latin-ext for seven letters. Here each
// face gets a tiny file with just those characters; the original latin-ext file stays declared for everything else in
// its range, so a rarer letter still renders in the right font (and only then is that file fetched).
// Vietnamese is dropped (never used); `woff` fallbacks are dropped (every supported browser reads woff2).
//
// Run with `npm run fonts` after changing a weight or a font package.
import {mkdirSync, readFileSync, writeFileSync} from "node:fs";
import subsetFont from "subset-font";

const FACES = [
    {pkg: "@fontsource-variable/inter", css: "index.css"},
    {pkg: "@fontsource/cormorant-garamond", css: "500.css"},
    {pkg: "@fontsource/cormorant-garamond", css: "600.css"},
    {pkg: "@fontsource/cormorant-garamond", css: "500-italic.css"},
    {pkg: "@fontsource/eb-garamond", css: "400.css"},
    {pkg: "@fontsource/eb-garamond", css: "500.css"},
    {pkg: "@fontsource/eb-garamond", css: "400-italic.css"},
];

/** The characters Azerbaijani (and the prices) take from latin-ext. */
const AZ_CODE_POINTS = [0x011e, 0x011f, 0x0130, 0x015e, 0x015f, 0x018f, 0x0259, 0x20bc];
const AZ_TEXT = String.fromCodePoint(...AZ_CODE_POINTS);

const OUT_CSS = "src/fonts.css";
const OUT_DIR = "src/assets/fonts";

const hex = (value) => value.toString(16).toUpperCase().padStart(4, "0");

/** "U+0100-02BA,U+20AD-20C0" → [[0x100, 0x2ba], [0x20ad, 0x20c0]] */
const parseRanges = (text) => text.split(",").map((part) => {
    const [start, end = start] = part.trim().replace(/^U\+/i, "").split("-");
    return [parseInt(start, 16), parseInt(end, 16)];
});

const formatRanges = (ranges) => ranges.map(([start, end]) => (start === end ? `U+${hex(start)}` : `U+${hex(start)}-${hex(end)}`)).join(",");

/** Cuts single code points out of a list of ranges. */
const subtract = (ranges, points) => ranges.flatMap(([start, end]) => {
    const pieces = [];
    let from = start;
    for (const point of [...points].sort((a, b) => a - b)) {
        if (point < from || point > end) continue;
        if (point > from) pieces.push([from, point - 1]);
        from = point + 1;
    }
    if (from <= end) pieces.push([from, end]);
    return pieces;
});

const fontFace = ({family, style, weight, url, format, range, note}) => `/* ${note} */
@font-face {
  font-family: ${family};
  font-style: ${style};
  font-display: swap;
  font-weight: ${weight};
  src: url(${url}) format('${format}');
  unicode-range: ${range};
}
`;

mkdirSync(OUT_DIR, {recursive: true});
const blocks = [];

for (const {pkg, css} of FACES) {
    const source = readFileSync(`node_modules/${pkg}/${css}`, "utf8");
    for (const [, note, body] of source.matchAll(/\/\* (.+?) \*\/\s*@font-face \{([\s\S]*?)\}/g)) {
        if (note.includes("vietnamese")) continue;
        const read = (property) => body.match(new RegExp(`${property}:\\s*([^;]+);`))[1].trim();
        const [, file, format] = read("src").match(/url\(\.\/files\/([^)]+\.woff2)\) format\('([^']+)'\)/);
        const face = {family: read("font-family"), style: read("font-style"), weight: read("font-weight"), format};
        const range = read("unicode-range");
        const url = `../node_modules/${pkg}/files/${file}`;

        if (!note.includes("latin-ext")) {
            blocks.push(fontFace({...face, url, range, note}));
            continue;
        }

        const small = await subsetFont(readFileSync(`node_modules/${pkg}/files/${file}`), AZ_TEXT, {targetFormat: "woff2"});
        const smallFile = file.replace("latin-ext", "az");
        writeFileSync(`${OUT_DIR}/${smallFile}`, small);
        blocks.push(fontFace({...face, url: `./assets/fonts/${smallFile}`, range: formatRanges(AZ_CODE_POINTS.map((point) => [point, point])), note: `${note.replace("latin-ext", "az")} (${small.length} bytes)`}));
        blocks.push(fontFace({...face, url, range: formatRanges(subtract(parseRanges(range), AZ_CODE_POINTS)), note: `${note} without the Azerbaijani letters`}));
    }
}

writeFileSync(OUT_CSS, `/* Generated by scripts/generate-fonts.mjs — do not edit by hand. */\n\n${blocks.join("\n")}`);
console.log(`Wrote ${blocks.length} @font-face rules to ${OUT_CSS}.`);
