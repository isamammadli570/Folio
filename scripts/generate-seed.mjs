// Builds supabase/migrations/0002_seed.sql from the catalogue in src/data, so the database starts with exactly the
// books and authors the storefront was built on. Run with `npm run db:seed-sql`; re-running replaces the file.
import {mkdirSync, rmSync, writeFileSync} from "node:fs";
import {dirname, join, resolve} from "node:path";
import {fileURLToPath, pathToFileURL} from "node:url";
import {build} from "rolldown";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const tmp = join(root, "node_modules", ".tmp", "seed");
mkdirSync(tmp, {recursive: true});

await build({
    input: {authors: join(root, "src/data/authors.ts"), books: join(root, "src/data/books.ts")},
    resolve: {alias: {"@": join(root, "src")}},
    output: {dir: tmp, format: "esm", entryFileNames: "[name].mjs"},
    logLevel: "silent",
});

const {AUTHORS} = await import(pathToFileURL(join(tmp, "authors.mjs")).href);
const {BOOKS} = await import(pathToFileURL(join(tmp, "books.mjs")).href);
rmSync(tmp, {recursive: true, force: true});

const text = (value) => (value === undefined || value === null ? "null" : `'${String(value).replaceAll("'", "''")}'`);
const json = (value) => (value === undefined || value === null ? "null" : `${text(JSON.stringify(value))}::jsonb`);
const num = (value) => (value === undefined || value === null ? "null" : String(value));
const bool = (value) => (value ? "true" : "false");

const authorRows = AUTHORS.map((a, index) =>
    `    (${[text(a.id), json(a.name), num(a.born), num(a.died), bool(a.approx), json(a.movement), json(a.bio), json(a.quote), num(a.featured), text(a.portrait), text(a.scene), num(index)].join(", ")})`,
);
const bookRows = BOOKS.map((b, index) =>
    `    (${[text(b.id), text(b.authorId), text(b.category), json(b.title), json(b.description), num(b.price), num(b.oldPrice), num(b.stock), num(b.pages), num(b.year), bool(b.approxYear), text(b.ornament), text(b.tag), text(b.coverImage), num(index)].join(", ")})`,
);

const sql = `-- Folio: catalogue seed, generated by scripts/generate-seed.mjs from src/data. Do not edit by hand.
-- ${AUTHORS.length} authors, ${BOOKS.length} books. Re-running updates the rows in place (stock is left alone once set).

insert into public.authors (id, name, born, died, approx, movement, bio, quote, featured, portrait, scene, position) values
${authorRows.join(",\n")}
on conflict (id) do update set
    name = excluded.name, born = excluded.born, died = excluded.died, approx = excluded.approx,
    movement = excluded.movement, bio = excluded.bio, quote = excluded.quote, featured = excluded.featured,
    portrait = excluded.portrait, scene = excluded.scene, position = excluded.position;

insert into public.books (id, author_id, category, title, description, price, old_price, stock, pages, year, approx_year, ornament, tag, cover_image, position) values
${bookRows.join(",\n")}
on conflict (id) do update set
    author_id = excluded.author_id, category = excluded.category, title = excluded.title,
    description = excluded.description, price = excluded.price, old_price = excluded.old_price, pages = excluded.pages,
    year = excluded.year, approx_year = excluded.approx_year, ornament = excluded.ornament, tag = excluded.tag,
    cover_image = excluded.cover_image, position = excluded.position;
`;

const out = join(root, "supabase/migrations/0002_seed.sql");
writeFileSync(out, sql);
console.log(`Wrote ${out}: ${AUTHORS.length} authors, ${BOOKS.length} books.`);
